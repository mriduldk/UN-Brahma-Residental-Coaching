<script>
    function updateSections() {
        const classSelect = document.getElementById('classSelect');
        const sectionSelect = document.getElementById('sectionSelect');
        if (!classSelect || !sectionSelect) return;

        const selectedOption = classSelect.options[classSelect.selectedIndex];
        
        // Clear existing sections
        sectionSelect.innerHTML = '<option value="">All Sections</option>';
        
        if (selectedOption && selectedOption.value && selectedOption.hasAttribute('data-sections')) {
            try {
                const sections = JSON.parse(selectedOption.getAttribute('data-sections'));
                const selectedSection = '{{ request('section_id') }}';
                
                sections.forEach(section => {
                    const option = document.createElement('option');
                    option.value = section.id;
                    option.textContent = section.name;
                    if (selectedSection == section.id) {
                        option.selected = true;
                    }
                    sectionSelect.appendChild(option);
                });
            } catch (e) {
                console.error('Error parsing sections json');
            }
        }
    }

    // Modal Logic
    const editModal = document.getElementById('editStudentModal');
    const editForm = document.getElementById('editStudentForm');

    function openEditModal(data) {
        // Set basic info
        document.getElementById('edit_enrollment_id').value = data.enrollment_id;
        document.getElementById('edit_full_name').value = data.name;
        document.getElementById('edit_email').value = data.email;
        document.getElementById('edit_phone_number').value = data.phone;
        document.getElementById('edit_academic_year_id').value = data.academic_year_id;
        document.getElementById('edit_class_id').value = data.class_id;
        
        // Set form action dynamically
        editForm.action = `/school/students/${data.id}`;

        // Handle sections
        updateModalSections(data.section_id);

        // Show modal
        editModal.classList.remove('hidden');
        document.body.classList.add('overflow-hidden');
    }

    function closeEditModal() {
        editModal.classList.add('hidden');
        document.body.classList.remove('overflow-hidden');
    }

    function updateModalSections(selectedSectionId = null) {
        const classSelect = document.getElementById('edit_class_id');
        const sectionSelect = document.getElementById('edit_section_id');
        if (!classSelect || !sectionSelect) return;

        const selectedOption = classSelect.options[classSelect.selectedIndex];
        
        sectionSelect.innerHTML = '<option value="">No Section</option>';
        
        if (selectedOption && selectedOption.hasAttribute('data-sections')) {
            try {
                const sections = JSON.parse(selectedOption.getAttribute('data-sections'));
                sections.forEach(section => {
                    const option = document.createElement('option');
                    option.value = section.id;
                    option.textContent = section.name;
                    if (selectedSectionId && selectedSectionId == section.id) {
                        option.selected = true;
                    }
                    sectionSelect.appendChild(option);
                });
            } catch (e) {
                console.error('Error parsing modal sections json');
            }
        }
    }

    // Close modal on escape key
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && !editModal.classList.contains('hidden')) {
            closeEditModal();
        }
    });

    // Close modal on click outside
    editModal.addEventListener('click', (e) => {
        if (e.target === editModal) {
            closeEditModal();
        }
    });

    function handleEditFormSubmit(form) {
        try {
            const submitBtn = form.querySelector('button[type="submit"]');
            if (!submitBtn) return true;

            // Disable button
            submitBtn.disabled = true;
            submitBtn.classList.add('opacity-75', 'cursor-not-allowed');
            
            // Update button content
            const updateText = submitBtn.querySelector('.update-text');
            const updateIcon = submitBtn.querySelector('.update-icon');
            
            if (updateText) updateText.textContent = 'Updating...';
            if (updateIcon) {
                updateIcon.outerHTML = `
                    <svg class="animate-spin h-5 w-5 text-white" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24">
                        <circle class="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" stroke-width="4"></circle>
                        <path class="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"></path>
                    </svg>
                `;
            }
        } catch (e) {
            console.error('Loading state failed:', e);
        }
        
        return true;
    }

    // Initialize on load
    document.addEventListener('DOMContentLoaded', updateSections);
</script>
